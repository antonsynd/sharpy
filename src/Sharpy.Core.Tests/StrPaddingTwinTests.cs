    private static string Apply(string method, string s, int width, string? fill) => (method, fill) switch
    {
        ("center", null) => s.Center(width),
        ("center", _) => s.Center(width, fill),
        ("ljust", null) => s.Ljust(width),
        ("ljust", _) => s.Ljust(width, fill),
        ("rjust", null) => s.Rjust(width),
        ("rjust", _) => s.Rjust(width, fill),
        _ => throw new ArgumentException(method),
    };

    [Fact]
    public void Padding_MatchesPythonTwinTable()
    {
        var mismatches = new List<string>();
        foreach (var (method, s, width, fill, expected) in Table)
        {
            var actual = Apply(method, s, width, fill);
            if (actual != expected)
                mismatches.Add($"'{s}'.{method}({width}{(fill == null ? "" : ", '" + fill + "'")}) = '{actual}', python '{expected}'");
        }

        Table.Should().HaveCount(300);
        mismatches.Should().BeEmpty();
    }

    [Theory]
    // python3: "x".center(5, "ab") -> TypeError: The fill character must be exactly one character long
    [InlineData("center", "")]
    [InlineData("center", "ab")]
    [InlineData("ljust", "")]
    [InlineData("ljust", "ab")]
    [InlineData("rjust", "")]
    [InlineData("rjust", "ab")]
    public void Padding_FillOfLengthOtherThanOne_IsTypeError(string method, string fill)
    {
        // Validated before the width check: CPython raises even when no padding is needed.
        foreach (var width in new[] { 5, 0 })
        {
            var act = () => Apply(method, "x", width, fill);
            act.Should().Throw<TypeError>().WithMessage("The fill character must be exactly one character long");
        }
    }
