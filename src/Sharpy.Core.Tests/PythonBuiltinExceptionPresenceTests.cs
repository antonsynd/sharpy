using SCG = System.Collections.Generic;
using System.Text.RegularExpressions;
using Sharpy.TestInfrastructure.Oracles;
using Xunit;

namespace Sharpy.Core.Tests;

/// <summary>
/// The absence control of the exception hierarchy: <see cref="ExceptionHierarchyPythonMroTests"/> measures the Core
/// exception types that EXIST; this measures that every builtin exception python names exists. A builtin python
/// raises or a program names that Core lacks is a refused <c>except</c>/<c>raise</c>, and no test of the existing
/// types notices it.
///
/// <para><b>Oracle.</b> <c>python-builtin-exceptions.txt</c>, generated by the command in its header with the pinned
/// oracle minor; <see cref="CommittedList_IsTheOraclesBuiltinExceptions"/> re-derives it from python at test time
/// (equal on the list's minor, a subset or superset on an older or newer one) so the list cannot drift.</para>
///
/// <para><b>Present</b>: a public exception type of the Core assembly of that name, or a spec ruling in
/// <c>exception_handling.md</c> — a row of its "Exception Type Hierarchy" table (<c>Exception</c> is
/// <c>System.Exception</c>, <c>IOError</c> is <c>OSError</c>) or a <c>## No `Name`</c> section
/// (<c>BaseException</c>).</para>
///
/// <para><b>Ratchet.</b> The absent set must equal <c>builtin-exception-absence-allowlist.txt</c>: a newly absent
/// name is red, a listed name that now exists is red (stale: delete the row).</para>
/// </summary>
public class PythonBuiltinExceptionPresenceTests
{
    private static readonly Regex AllowlistRow = new(@"^(?<name>[A-Za-z_]\w*) # #(?<issue>\d+) (?<reason>\S.*)$", RegexOptions.Compiled);
    private static readonly Regex VersionLine = new(@"^# python 3\.(?<minor>\d+)$", RegexOptions.Compiled);

    private const string OracleScript = """
        import builtins, sys
        sys.stdin.read()
        names = sorted(n for n, v in vars(builtins).items()
                       if isinstance(v, type) and issubclass(v, BaseException) and not n.startswith("_"))
        print(f"{sys.version_info.minor}")
        for n in names:
            print(n)
        """;

    [Fact]
    public void EveryPythonBuiltinException_ExistsInCore_BeyondTheAllowlist()
    {
        var (names, _) = ReadCommittedList();
        var allowed = ReadAllowlist();
        var absent = names.Where(n => !IsPresent(n)).ToList();

        var unlisted = absent.Where(n => !allowed.ContainsKey(n)).ToList();
        var stale = allowed.Keys.Where(n => !absent.Contains(n)).OrderBy(n => n, StringComparer.Ordinal).ToList();
        Assert.True(unlisted.Count == 0 && stale.Count == 0,
            "Python builtin exceptions absent from Sharpy.Core disagree with builtin-exception-absence-allowlist.txt.\n"
            + "Absent and unlisted (add the type, or list it citing its OPEN issue):\n  " + string.Join("\n  ", unlisted)
            + "\nListed but present (delete the row):\n  " + string.Join("\n  ", stale));
    }

    /// <summary>Positive control: the predicate sees a Core type, both kinds of spec ruling, and a known absence.</summary>
    [Fact]
    public void PositiveControl_PresenceSeesCoreTypesAndSpecRulings()
    {
        Assert.True(IsPresent("ValueError"));
        Assert.True(IsPresent("FileNotFoundError"));
        Assert.True(IsPresent("Exception"));
        Assert.True(IsPresent("IOError"));
        Assert.True(IsPresent("BaseException"));
        Assert.False(IsPresent("TimeoutError"));
        Assert.False(IsPresent("NoSuchError"));
        var (names, minor) = ReadCommittedList();
        Assert.True(names.Count >= 60, $"the committed list holds only {names.Count} names");
        Assert.Contains("ValueError", names);
        Assert.True(minor >= 9);
    }

    /// <summary>
    /// The committed list agrees with the running interpreter's builtins, whatever its minor (3.9+): equal on the
    /// list's own minor; on an older minor the interpreter's names are a subset (python adds builtin exceptions,
    /// e.g. 3.13's <c>PythonFinalizationError</c>, 3.15's <c>ImportCycleError</c>); on a newer one, a superset.
    /// </summary>
    [SkippableFact]
    public void CommittedList_IsTheOraclesBuiltinExceptions()
    {
        var (names, minor) = ReadCommittedList();
        var python = PythonInterpreter.RequireOrSkip(9);

        var script = Path.Combine(Path.GetTempPath(), $"sharpy-builtin-exceptions-{Guid.NewGuid():N}.py");
        File.WriteAllText(script, OracleScript);
        try
        {
            var lines = python.RunBatch(script, new[] { "{}" });
            Assert.Equal(python.Minor.ToString(System.Globalization.CultureInfo.InvariantCulture), lines[0]);
            var live = lines.Skip(1).ToArray();
            Assert.True(live.Length >= 60, $"python 3.{python.Minor} reported only {live.Length} builtin exceptions");
            if (python.Minor == minor)
            {
                Assert.Equal(live, names.ToArray());
            }
            else
            {
                var (older, newer) = python.Minor < minor ? (live, names.ToArray()) : (names.ToArray(), live);
                var missing = older.Except(newer, StringComparer.Ordinal).ToList();
                Assert.True(missing.Count == 0,
                    $"python 3.{python.Minor} and the committed 3.{minor} list disagree beyond added names; " +
                    $"in the older but not the newer: {string.Join(", ", missing)}");
            }
        }
        finally
        {
            File.Delete(script);
        }
    }

    private static readonly Lazy<HashSet<string>> CoreNames = new(() =>
        new HashSet<string>(
            typeof(KeyError).Assembly.GetExportedTypes()
                .Where(t => typeof(Exception).IsAssignableFrom(t))
                .Select(t => t.Name),
            StringComparer.Ordinal));

    private static readonly Lazy<HashSet<string>> SpecRuled = new(ReadSpecRulings);

    private static bool IsPresent(string name) => CoreNames.Value.Contains(name) || SpecRuled.Value.Contains(name);

    private static HashSet<string> ReadSpecRulings()
    {
        var path = PythonInterpreter.FindRepoFile("docs", "language_specification", "exception_handling.md")
            ?? throw new InvalidOperationException("docs/language_specification/exception_handling.md not found above the test binary.");
        var row = new Regex(@"^\|\s*`([A-Za-z_]\w*)`\s*\|", RegexOptions.CultureInvariant);
        var noSection = new Regex(@"^## No `([A-Za-z_]\w*)`\s*$", RegexOptions.CultureInvariant);
        var result = new HashSet<string>(StringComparer.Ordinal);
        var inTable = false;
        foreach (var line in File.ReadLines(path))
        {
            if (line.StartsWith("## ", StringComparison.Ordinal) || line.StartsWith("### ", StringComparison.Ordinal))
            {
                inTable = line.Trim() == "## Exception Type Hierarchy";
                var no = noSection.Match(line);
                if (no.Success)
                    result.Add(no.Groups[1].Value);
                continue;
            }
            if (inTable && row.Match(line) is { Success: true } m)
                result.Add(m.Groups[1].Value);
        }
        Assert.Contains("Exception", result);
        Assert.Contains("BaseException", result);
        return result;
    }

    private static (SCG.List<string> Names, int Minor) ReadCommittedList()
    {
        var path = PythonInterpreter.FindRepoFile("src", "Sharpy.Core.Tests", "python-builtin-exceptions.txt")
            ?? throw new FileNotFoundException("src/Sharpy.Core.Tests/python-builtin-exceptions.txt not found above the test binary.");
        var names = new SCG.List<string>();
        int minor = -1;
        foreach (var raw in File.ReadAllLines(path))
        {
            var line = raw.Trim();
            if (VersionLine.Match(line) is { Success: true } v)
                minor = int.Parse(v.Groups["minor"].Value, System.Globalization.CultureInfo.InvariantCulture);
            if (line.Length == 0 || line.StartsWith('#'))
                continue;
            names.Add(line);
        }
        Assert.True(minor > 0, "python-builtin-exceptions.txt has no `# python 3.N` header line");
        return (names, minor);
    }

    private static Dictionary<string, string> ReadAllowlist()
    {
        var path = PythonInterpreter.FindRepoFile("src", "Sharpy.Core.Tests", "builtin-exception-absence-allowlist.txt")
            ?? throw new FileNotFoundException("src/Sharpy.Core.Tests/builtin-exception-absence-allowlist.txt is missing; its presence arms the ratchet.");
        var rows = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var raw in File.ReadAllLines(path))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line.StartsWith('#'))
                continue;
            var m = AllowlistRow.Match(line);
            Assert.True(m.Success, $"malformed row (want `Name # #N reason`): {line}");
            Assert.False(rows.ContainsKey(m.Groups["name"].Value), $"duplicate row: {line}");
            rows[m.Groups["name"].Value] = m.Groups["issue"].Value;
        }
        return rows;
    }
}
