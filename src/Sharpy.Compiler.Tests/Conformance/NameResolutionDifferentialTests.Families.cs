    private sealed record MemberShape(string Kind, string Member, string[] Decl, string Expr, int Value, bool Chainable = false, string? Chained = null);

    /// <summary>TYPEMEMBER's shapes, each a generated pair of <see cref="NameResolutionRosters.TypeMemberShapes"/> (P77b D5): a
    /// shape on a pair the roster excludes or lacks is a generator failure. The union's constructor is generated by its own
    /// arm in <see cref="TypeMemberCells"/>.</summary>
    private static IEnumerable<MemberShape> MemberShapes()
        => RenderedMemberShapes().Select(s =>
            NameResolutionRosters.TypeMemberShapes.TryGetValue((s.Kind, s.Member), out var m) && m.Generated
                ? s
                : throw new InvalidOperationException($"TYPEMEMBER shape {s.Kind}/{s.Member} is not generated on TypeMemberShapes"));

    private static IEnumerable<MemberShape> RenderedMemberShapes()
    {
        foreach (var (kind, header) in new[] { ("class", new[] { "class Later:" }), ("struct", new[] { "struct Later:" }), ("dataclass", new[] { "@dataclass", "class Later:" }) })
        {
            string[] D(params string[] body) => header.Concat(Indent(new[] { "def me(self) -> Later:", "    return self" }.Concat(body))).ToArray();
            yield return new(kind, "method", D("def get(self) -> int:", "    return 1"), "Later().get()", 1, true, "Later().me().get()");
            yield return new(kind, "property", D("property p: int = 1"), "Later().p", 1, true, "Later().me().p");
            yield return new(kind, "field", D("f: int = 1"), "Later().f", 1, true, "Later().me().f");
            yield return new(kind, "static-method", D("@static", "def s() -> int:", "    return 1"), "Later.s()", 1);
            string[] ctor = kind == "class"
                ? D("v: int = 0", "def __init__(self, v: int) -> None:", "    self.v = v")
                : D("v: int = 0");
            yield return new(kind, "constructor", ctor, "Later(3).v", 3, true, "Later(3).me().v");
        }

        yield return new("enum", "case", new[] { "enum Later:", "    RED = 1" }, "Later.RED.value", 1);

        string[] iface = { "interface Later:", "    def get(self) -> int: ...", "class C(Later):", "    def get(self) -> int:", "        return 1", "def via(i: Later) -> int:", "    return i.get()" };
        yield return new("interface", "method", iface, "via(C())", 1);
        string[] ifaceProp = { "interface Later:", "    property p: int", "class C(Later):", "    property p: int = 1", "def via(i: Later) -> int:", "    return i.p" };
        yield return new("interface", "property", ifaceProp, "via(C())", 1);
        yield return new("interface", "field", new[] { "interface Later:", "    const K: int = 1" }, "Later.K", 1);

        string[] unionMethod = { "union Later:", "    case V(f: int)", "    case L()", "    def get(self) -> int:", "        return 1" };
        yield return new("union", "method", unionMethod, "Later.V(3).get()", 1);
    }

    private static NameCell TypeMemberCell(string label, IEnumerable<string> decl, IEnumerable<string> main, IReadOnlyList<string>? support, string model, Order order, string kind)
    {
        var mainBlock = MainBlock(main.ToArray());
        var declText = Join(decl);
        var supportText = support == null ? "" : Join(support);
        var source = order == Order.Earlier
            ? declText + supportText + mainBlock
            : supportText + mainBlock + declText;
        return new NameCell
        {
            Id = CellId("typemember", kind, label, order == Order.Earlier ? "before" : "after"),
            Family = Family.TypeMember,
            Source = source,
            Tag = SharpyTag.MustRun,
            Model = model,
            Python = PyOutcome.Ran(model),
            Rule = "P52",
            Target = kind switch
            {
                "struct" => BindingKind.ModuleStruct,
                "enum" => BindingKind.ModuleEnum,
                "union" => BindingKind.ModuleUnion,
                "interface" => BindingKind.ModuleInterface,
                _ => BindingKind.ModuleClass,
            },
            Outer = BindingKind.None,
        };
    }

    private static IEnumerable<NameCell> TypeMemberCells()
    {
        foreach (var order in new[] { Order.Earlier, Order.Later })
        {
            foreach (var m in MemberShapes())
            {
                foreach (var spelling in m.Kind is "interface" or "enum" ? new[] { "bare" } : new[] { "bare", "alias" })
                {
                    var alias = spelling == "alias";
                    var decl = alias ? m.Decl.Append("type A = Later").ToArray() : m.Decl;
                    string Spell(string e) => alias ? e.Replace("Later", "A", StringComparison.Ordinal) : e;
                    var e = Spell(m.Expr);
                    string v = Str(m.Value);
                    string prefix = $"{m.Member}/{spelling}/";

                    yield return TypeMemberCell(prefix + "store", decl, new[] { $"x0: int = {e}", "print(x0)" }, null, v, order, m.Kind);
                    yield return TypeMemberCell(prefix + "match", decl, new[] { $"match {e}:", $"    case {v}:", $"        print({v})", "    case _:", "        print(0)" }, null, v, order, m.Kind);
                    yield return TypeMemberCell(prefix + "argument", decl, new[] { $"show({e})" }, new[] { "def show(a: int) -> None:", "    print(a)" }, v, order, m.Kind);
                    yield return TypeMemberCell(prefix + "condition", decl, new[] { $"if {e} == {v}:", $"    print({v})" }, null, v, order, m.Kind);
                    yield return TypeMemberCell(prefix + "return", decl, new[] { "print(g0())" }, new[] { "def g0() -> int:", $"    return {e}" }, v, order, m.Kind);
                    if (m.Chained != null)
                        yield return TypeMemberCell(prefix + "chained", decl, new[] { $"print({Spell(m.Chained)})" }, null, v, order, m.Kind);
                }
            }

            // A T? method matched on Some (the #2249 shape), through D1's Some shim in the twin.
            string[] optional = { "class Later:", "    def get(self) -> int?:", "        return Some(1)" };
            yield return TypeMemberCell("optional-method/bare/match", optional,
                new[] { "match Later().get():", "    case Some(v):", "        print(v)", "    case _:", "        print(0)" }, null, "1", order, "class");

            // A union's member is its case constructor, read through the match.
            string[] union = { "union Later:", "    case V(f: int)", "    case L()" };
            yield return TypeMemberCell("constructor/bare/match", union,
                new[] { "match Later.V(3):", "    case V(v):", "        print(v)", "    case _:", "        print(0)" }, null, "3", order, "union");
            yield return TypeMemberCell("constructor/alias/match", union.Append("type A = Later"),
                new[] { "match A.V(3):", "    case V(v):", "        print(v)", "    case _:", "        print(0)" }, null, "3", order, "union");
            yield return TypeMemberCell("constructor/bare/store-then-match", union,
                new[] { "u0: Later = Later.V(3)", "match u0:", "    case V(v):", "        print(v)", "    case L():", "        print(0)" }, null, "3", order, "union");

            // The pattern position: the sub-axis is roster 7, every Pattern subclass by class.
            string[] cls = { "class Later:", "    pass", "class Other:", "    pass" };
            string[] dc = { "@dataclass", "class Later:", "    v: int = 3" };
            string[] st = { "struct Later:", "    v: int = 3" };
            string[] constHost = { "class Later:", "    const K: int = 1" };
            string[] en = { "enum Later:", "    RED = 1", "    BLUE = 2" };

            string[] Arm(string scrutinee, string pattern, string body) => new[] { $"match {scrutinee}:", $"    case {pattern}:", $"        print({body})", "    case _:", "        print(0)" };

            yield return TypeMemberCell("pattern/TypePattern", cls, new[] { "o: object = Later()" }.Concat(Arm("o", "Later()", "1")), null, "1", order, "class");
            // No BindingPattern-typed cell and no AndPattern cell: each has a NameResolutionRosters.PatternNotes entry saying why.
            yield return TypeMemberCell("pattern/MemberAccessPattern-enum", en, Arm("Later.RED", "Later.RED", "1"), null, "1", order, "enum");
            yield return TypeMemberCell("pattern/MemberAccessPattern-const", constHost, Arm("1", "Later.K", "1"), null, "1", order, "class");
            yield return TypeMemberCell("pattern/PositionalPattern-dataclass", dc, Arm("Later()", "Later(v)", "v"), null, "3", order, "dataclass");
            yield return TypeMemberCell("pattern/PositionalPattern-struct", st, Arm("Later()", "Later(v)", "v"), null, "3", order, "struct");
            yield return TypeMemberCell("pattern/PropertyPattern-dataclass", dc, Arm("Later()", "Later(v=x)", "x"), null, "3", order, "dataclass");
            yield return TypeMemberCell("pattern/PropertyPattern-struct", st, Arm("Later()", "Later(v=x)", "x"), null, "3", order, "struct");
            yield return TypeMemberCell("pattern/OrPattern", cls, new[] { "o: object = Later()" }.Concat(Arm("o", "Later() | Other()", "1")), null, "1", order, "class");
            yield return TypeMemberCell("pattern/GuardPattern", cls, new[] { "o: object = Later()" }.Concat(Arm("o", "Later() if True", "1")), null, "1", order, "class");
            yield return TypeMemberCell("pattern/AsPattern", cls, new[] { "o: object = Later()" }.Concat(Arm("o", "Later() as l0", "1")), null, "1", order, "class");
            yield return TypeMemberCell("pattern/TuplePattern", cls, Arm("(Later(), 1)", "(Later(), _)", "1"), null, "1", order, "class");
            yield return TypeMemberCell("pattern/ListPattern", cls, Arm("[Later()]", "[Later()]", "1"), null, "1", order, "class");
        }
    }

