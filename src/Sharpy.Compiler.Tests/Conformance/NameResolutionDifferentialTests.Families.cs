    private enum StoreSpelling
    {
        Assign,
        Augmented,
        Walrus,
        OutLet,
        Let,
        Annotated,
    }

    private static string StoreText(StoreSpelling s, string name) => s switch
    {
        StoreSpelling.Assign => $"{name} = 15",
        StoreSpelling.Augmented => $"{name} += 1",
        StoreSpelling.Walrus => $"({name} := 15)",
        StoreSpelling.OutLet => $"f0(out let {name})",
        StoreSpelling.Let => $"let {name} = 15",
        StoreSpelling.Annotated => $"{name}: int = 15",
        _ => throw new ArgumentOutOfRangeException(nameof(s)),
    };

    private static StoreForm FormEnum(StoreSpelling s) => s switch
    {
        StoreSpelling.Assign => StoreForm.Assign,
        StoreSpelling.Augmented => StoreForm.Augmented,
        StoreSpelling.Walrus => StoreForm.Walrus,
        StoreSpelling.OutLet => StoreForm.OutLet,
        _ => StoreForm.LetOrVar,
    };

    private static bool IsFreshBinding(StoreSpelling s) => s is StoreSpelling.OutLet or StoreSpelling.Let or StoreSpelling.Annotated;

    private static bool IsWritableModule(BindingKind k) => k is BindingKind.ModuleVar or BindingKind.ModuleProperty;
    private static bool IsConstKind(BindingKind k) => k is BindingKind.ModuleLiteralConst or BindingKind.ModuleComputedConst;
    private static bool IsNonWritableByMeaning(BindingKind k) => k is BindingKind.ModuleDef or BindingKind.ModuleClass or BindingKind.ModuleStruct
        or BindingKind.ModuleEnum or BindingKind.ModuleUnion or BindingKind.ModuleInterface or BindingKind.ModuleTypeAlias;
    private static bool IsTypeLevelMember(BindingKind k) => k is BindingKind.StaticField or BindingKind.StaticProperty or BindingKind.StaticMethod
        or BindingKind.ClassLiteralConst or BindingKind.ClassComputedConst or BindingKind.InstanceField or BindingKind.InstanceProperty or BindingKind.InstanceMethod;

    /// <summary>D3.e STORE's rule, keyed on (form, outer writability class).</summary>
    private static Expected ExpectStore(StoreSpelling s, BindingKind outer, bool declared, int outerValue, bool laterRead)
    {
        string After(object first) => laterRead ? JoinOut(first, outerValue) : JoinOut(first);
        var local = PyOutcome.Ran(After(15));
        var pyNoDecl = s == StoreSpelling.Augmented ? PyOutcome.Unbound("x") : local;

        if (declared)
        {
            object written = s == StoreSpelling.Augmented ? outerValue + 1 : 15;
            var through = PyOutcome.Ran(laterRead ? JoinOut(written, written) : JoinOut(written));
            if (IsConstKind(outer))
                return Refuse(through, "kind:SPY0225");
            if (IsNonWritableByMeaning(outer))
            {
                // `x += 1` on a def or type raises. `x = 15` runs, and the later read then spells the type's own read on an int.
                // P77b D6 R-KY (D11): a store to a def / type-kind name is refused in every form, `global` included (#2424).
                var overwritten = s == StoreSpelling.Augmented || laterRead
                    ? PyOutcome.Other(s != StoreSpelling.Augmented && outer == BindingKind.ModuleEnum ? "AttributeError" : "TypeError")
                    : through;
                return Refuse(overwritten, "N6-type-kind");
            }
            return new Expected(SharpyTag.MustRun, through.Value, through, "N6");
        }

        if (IsFreshBinding(s))
            return new Expected(SharpyTag.MustRun, local.Value, local, s == StoreSpelling.OutLet ? "R-BM" : "#1974");

        if (outer == BindingKind.None)
        {
            return s == StoreSpelling.Augmented
                ? Refuse(PyOutcome.Unbound("x"), "N5")
                : new Expected(SharpyTag.MustRun, "15", PyOutcome.Ran(15), "N5");
        }

        if (IsTypeLevelMember(outer))
        {
            // variable_scoping.md, "Every store form is refused": a bare store to a class member is SPY0606 in every form, though
            // python makes it a local. Only a method's name is still a local here: the spec's sentence reads as covering it and the
            // compiler lets it through, and that question is posted on #2427.
            return s == StoreSpelling.Augmented || !(outer is BindingKind.StaticMethod or BindingKind.InstanceMethod)
                ? Refuse(pyNoDecl, "SPY0606")
                : new Expected(SharpyTag.MustRun, local.Value, local, "R-Y");
        }
        if (IsConstKind(outer))
            return Refuse(pyNoDecl, "kind:SPY0225");
        // P77b D6 R-KY (D11): B24's refusal applied to every def / type-kind name, in every form (#2424).
        if (IsNonWritableByMeaning(outer))
            return Refuse(pyNoDecl, "N6-type-kind");
        return Refuse(pyNoDecl, "N6");
    }

    private static NameCell ModuleStoreCell(StoreSpelling s, BindingKind outer, ReadPosition body, bool declared, bool laterRead, Order order, bool insideIf)
    {
        var n = ReadName.Plain;
        var stmts = new List<string>();
        if (declared)
            stmts.Add("global x");
        if (insideIf)
            stmts.AddRange(new[] { "if True:", "    " + StoreText(s, "x") });
        else
            stmts.Add(StoreText(s, "x"));
        stmts.Add("print(x)");

        var members = IsTypeLevelMember(outer) ? MemberDecl(outer, n) : new List<string>();
        var (host, call) = Host(body, stmts, members);
        var lines = new List<string>();
        if (s == StoreSpelling.OutLet)
            lines.AddRange(OutLetHelper);
        var decl = outer == BindingKind.None || IsTypeLevelMember(outer) ? new List<string>()
            : outer == BindingKind.ModuleUnion ? UnionDecl.ToList()
            : outer == BindingKind.ModuleInterface ? InterfaceDecl.ToList()
            : ModuleDecl(outer, n);
        if (order == Order.Earlier)
            lines.AddRange(decl.Concat(host));
        else
            lines.AddRange(host.Concat(decl));

        var main = new List<string>(call);
        string? read = outer == BindingKind.None ? null
            : IsTypeLevelMember(outer) ? TypeLevelRead(outer, n)
            : OuterRead(outer, n);
        bool reads = laterRead && read != null;
        if (reads)
            main.Add($"print({read})");
        int outerValue = outer is BindingKind.None or BindingKind.ModuleUnion or BindingKind.ModuleInterface ? 0 : ValueOf(outer);
        var expected = ExpectStore(s, outer, declared, outerValue, reads);
        return new NameCell
        {
            Id = CellId("store", s, $"outer={outer}", body, declared ? "global" : "no-decl", order, laterRead ? "later-read" : "no-read", insideIf ? "inside-if" : null),
            Family = Family.Store,
            Source = WithHelpers(Join(lines) + MainBlock(main.ToArray())),
            Tag = expected.Tag,
            Model = expected.Model,
            Python = expected.Python,
            Rule = expected.Rule,
            Target = outer,
            Outer = outer,
            Position = body,
            Form = FormEnum(s),
        };
    }

    /// <summary>The union and interface declarations of the name <c>x</c>: neither has an expression read, so STORE spells them
    /// as the outer it stores over, and D3.1's round trip declares them.</summary>
    private static readonly string[] UnionDecl = { "union x:", "    case V(f: int)", "    case L()" };

    private static readonly string[] InterfaceDecl = { "interface x:", "    def m(self) -> int: ..." };

    private static string TypeLevelRead(BindingKind k, ReadName n)
    {
        var prefix = IsInstance(k) ? "H()." : "H.";
        return ReadText(FormOf(k), prefix, n);
    }

    private static NameCell EnclosingStoreCell(StoreSpelling s, ReadPosition body, bool declared, bool insideIf)
    {
        // The host's OUTER function holds the enclosing local; the store crosses into it from a nested def.
        var inner = new List<string> { "def g() -> None:" };
        if (declared)
            inner.Add("    nonlocal x");
        if (insideIf)
            inner.AddRange(new[] { "    if True:", "        " + StoreText(s, "x") });
        else
            inner.Add("    " + StoreText(s, "x"));
        inner.Add("    print(x)");
        var stmts = new List<string> { "x: int = 13" };
        stmts.AddRange(inner);
        stmts.Add("g()");
        stmts.Add("print(x)");
        var (host, call) = Host(body, stmts);
        var lines = new List<string>();
        if (s == StoreSpelling.OutLet)
            lines.AddRange(OutLetHelper);
        lines.AddRange(host);
        var expected = ExpectStore(s, BindingKind.EnclosingLocal, declared, 13, laterRead: true);
        return new NameCell
        {
            Id = CellId("store", s, "outer=EnclosingLocal", body, declared ? "nonlocal" : "no-decl", insideIf ? "inside-if" : null),
            Family = Family.Store,
            Source = WithHelpers(Join(lines) + MainBlock(call.ToArray())),
            Tag = expected.Tag,
            Model = expected.Model,
            Python = expected.Python,
            Rule = expected.Rule,
            Target = BindingKind.EnclosingLocal,
            Outer = BindingKind.EnclosingLocal,
            Position = body,
            Form = FormEnum(s),
        };
    }

    /// <summary>The store of a binding of the same function: the two target scopes that never cross a boundary.</summary>
    private static NameCell SameFunctionStoreCell(StoreSpelling s, ReadPosition body, bool enclosingBlock)
    {
        var stmts = new List<string> { "x: int = 13" };
        if (enclosingBlock)
            stmts.AddRange(new[] { "if True:", "    " + StoreText(s, "x") });
        else
            stmts.Add(StoreText(s, "x"));
        stmts.Add("print(x)");
        var (host, call) = Host(body, stmts);
        int value = s == StoreSpelling.Augmented ? 14 : 15;
        return new NameCell
        {
            Id = CellId("store", s, "outer=LocalVar", body, enclosingBlock ? "enclosing-block" : "same-block"),
            Family = Family.Store,
            Source = WithHelpers(Join(host) + MainBlock(call.ToArray())),
            Tag = SharpyTag.MustRun,
            Model = Str(value),
            Python = PyOutcome.Ran(value),
            Rule = "N6-same-function",
            Target = BindingKind.LocalVar,
            Outer = BindingKind.LocalVar,
            Position = body,
            Form = FormEnum(s),
        };
    }

    private static IEnumerable<NameCell> StoreCells()
    {
        var crossing = new[] { StoreSpelling.Assign, StoreSpelling.Augmented, StoreSpelling.Walrus };
        var fresh = new[] { StoreSpelling.OutLet, StoreSpelling.Let, StoreSpelling.Annotated };
        var all = crossing.Concat(fresh).ToArray();
        // The outer axis is the roster's, filtered by what each arm below spells. The roster's EnclosingLocal, Builtin and None
        // arms are generated below.
        var moduleOuters = NameResolutionRosters.StoreOuter
            .Where(e => e.Value.Generated && !e.Value.ClassEnclosedBodiesOnly && IsModuleLevel(e.Key))
            .Select(e => e.Key)
            .OrderBy(k => k)
            .ToArray();
        var typeLevelOuters = NameResolutionRosters.StoreOuter
            .Where(e => e.Value.Generated && e.Value.ClassEnclosedBodiesOnly)
            .Select(e => e.Key)
            .OrderBy(k => k)
            .ToArray();

        // Every form × every module-level outer × the two representative bodies; ModuleVar × the whole body roster.
        foreach (var s in all)
        {
            foreach (var u in moduleOuters)
                foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
                    yield return ModuleStoreCell(s, u, body, false, true, Order.Earlier, false);

            foreach (var body in StoreBodiesFor(FormEnum(s)).Where(b => b is not (ReadPosition.FunctionBody or ReadPosition.MethodBody)))
                yield return ModuleStoreCell(s, BindingKind.ModuleVar, body, false, true, Order.Earlier, false);

            // Order and the no-later-read control, on the ModuleVar outer only (N6 has one answer per form).
            foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
            {
                yield return ModuleStoreCell(s, BindingKind.ModuleVar, body, false, true, Order.Later, false);
                yield return ModuleStoreCell(s, BindingKind.ModuleVar, body, false, false, Order.Earlier, false);
            }

            // No outer binding at all.
            foreach (var body in StoreBodiesFor(FormEnum(s)))
                yield return ModuleStoreCell(s, BindingKind.None, body, false, false, Order.Earlier, false);

            // The enclosing local.
            foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
                yield return EnclosingStoreCell(s, body, false, false);

            // The type-level outers (finding 1): the kinds of roster 1, from method-like bodies.
            foreach (var u in typeLevelOuters)
            {
                yield return ModuleStoreCell(s, u, ReadPosition.MethodBody, false, true, Order.Earlier, false);
                yield return ModuleStoreCell(s, u, ReadPosition.StaticMethodBody, false, true, Order.Earlier, false);
            }
        }

        // The declarations.
        foreach (var s in crossing)
        {
            foreach (var u in moduleOuters)
                yield return ModuleStoreCell(s, u, ReadPosition.FunctionBody, true, true, Order.Earlier, false);
            foreach (var body in new[] { ReadPosition.MethodBody, ReadPosition.NestedDefInFunction })
                yield return ModuleStoreCell(s, BindingKind.ModuleVar, body, true, true, Order.Earlier, false);
            yield return ModuleStoreCell(s, BindingKind.ModuleVar, ReadPosition.FunctionBody, true, true, Order.Later, false);
            foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
                yield return EnclosingStoreCell(s, body, true, false);
            foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
                foreach (var enclosingBlock in new[] { false, true })
                    yield return SameFunctionStoreCell(s, body, enclosingBlock);
        }

        // Store nesting: one Block family stands for all of them (`=` only), with its reason in the roster.
        foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
        {
            yield return ModuleStoreCell(StoreSpelling.Assign, BindingKind.ModuleVar, body, false, true, Order.Earlier, true);
            yield return EnclosingStoreCell(StoreSpelling.Assign, body, false, true);
        }

        // A walrus crossing a lambda, and a walrus inside a comprehension (the deviation row's feeder).
        foreach (var u in new[] { BindingKind.ModuleVar, BindingKind.EnclosingLocal })
            yield return LambdaWalrusCell(u);
        foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
            foreach (var u in new[] { BindingKind.None, BindingKind.ModuleVar })
                yield return WalrusInComprehensionCell(body, u);

        foreach (var cell in BuiltinStoreCells())
            yield return cell;
        foreach (var cell in ImportedStoreCells())
            yield return cell;
    }

    /// <summary>STORE × the ImportedName outer (P77b axis 9, D2.9): a bare store in a function or a method over the module's
    /// imported name. Python makes it a function local; N6 refuses a bare store over a module binding (p22). The stored value
    /// is a str, type-compatible with the str import (D3.a's non-coincidence rule; lead ruling on p22): an int store is
    /// refused by a TYPE error (SPY0220 / SPY0222) before the name verdict, which masks the cell.</summary>
    private static IEnumerable<NameCell> ImportedStoreCells()
    {
        var n = Imported;
        foreach (var s in new[] { StoreSpelling.Assign, StoreSpelling.Augmented, StoreSpelling.Walrus })
            foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
            {
                var text = s switch
                {
                    StoreSpelling.Assign => $"{n.Name} = \"abc\"",
                    StoreSpelling.Augmented => $"{n.Name} += \"x\"",
                    _ => $"({n.Name} := \"abc\")",
                };
                var (host, call) = Host(body, new[] { text, $"print({n.Name})" });
                var main = call.Append($"print({ReadText(Form.Value, "", n)})").ToArray();
                var python = s == StoreSpelling.Augmented ? PyOutcome.Unbound(n.Name) : PyOutcome.Ran(JoinOut("abc", n.BuiltinResult!.Value));
                var e = Refuse(python, "N6");
                yield return new NameCell
                {
                    Id = CellId("store", s, "outer=ImportedName", body, "no-decl", n.Name),
                    Family = Family.Store,
                    Source = WithImport(n, Join(host) + MainBlock(main)),
                    Tag = e.Tag,
                    Model = e.Model,
                    Python = e.Python,
                    Rule = e.Rule,
                    Target = BindingKind.ImportedName,
                    Outer = BindingKind.ImportedName,
                    Position = body,
                    Form = FormEnum(s),
                    NeedsStdlib = true,
                };
            }
    }

    private static NameCell LambdaWalrusCell(BindingKind outer)
    {
        var enclosing = outer == BindingKind.EnclosingLocal;
        var stmts = new List<string>();
        if (enclosing)
            stmts.Add("x: int = 13");
        stmts.AddRange(new[] { "g: () -> int = lambda: (x := 15)", "print(g())", "print(x)" });
        var (host, call) = Host(ReadPosition.FunctionBody, stmts);
        var lines = enclosing ? host : new[] { "x: int = 5" }.Concat(host);
        var value = enclosing ? 13 : 5;
        return new NameCell
        {
            Id = CellId("store", "lambda-walrus", $"outer={outer}"),
            Family = Family.Store,
            Source = Join(lines) + MainBlock(call.ToArray()),
            Tag = SharpyTag.MustRefuse,
            Python = PyOutcome.Ran(JoinOut(15, value)),
            Rule = "N6",
            Target = outer,
            Outer = outer,
            Position = ReadPosition.LambdaStored,
            Form = StoreForm.Walrus,
        };
    }

    private static NameCell WalrusInComprehensionCell(ReadPosition body, BindingKind outer)
    {
        var stmts = new[] { "ys: list[int] = [(x := v * 2) for v in [3]]", "print(x)" };
        var (host, call) = Host(body, stmts);
        var lines = outer == BindingKind.ModuleVar ? new[] { "x: int = 5" }.Concat(host) : host;
        var moduleOuter = outer == BindingKind.ModuleVar;
        return new NameCell
        {
            Id = CellId("store", "walrus-in-comprehension", $"outer={outer}", body),
            Family = Family.Store,
            Source = Join(lines) + MainBlock(call.ToArray()),
            Tag = moduleOuter ? SharpyTag.MustRun : SharpyTag.MustRefuse,
            Model = moduleOuter ? "5" : null,
            Python = PyOutcome.Ran(6),
            Rule = "N5",
            Deviation = "walrus-in-comprehension-scope",
            Target = outer,
            Outer = outer,
            Position = ReadPosition.ComprehensionElement,
            Form = StoreForm.Walrus,
        };
    }

    private static IEnumerable<NameCell> BuiltinStoreCells()
    {
        foreach (var (name, args, _, result) in Builtins)
        {
            NameCell Cell(string label, IReadOnlyList<string> lines, string[] main, Expected e, StoreForm form) => new()
            {
                Id = CellId("store", "builtin", label, name),
                Family = Family.Store,
                Source = Join(lines) + MainBlock(main),
                Tag = e.Tag,
                Model = e.Model,
                Python = e.Python,
                Rule = e.Rule,
                Target = BindingKind.ModuleVar,
                Outer = BindingKind.Builtin,
                Position = ReadPosition.FunctionBody,
                Form = form,
            };

            string[] Fn(params string[] body) => new[] { "def f() -> None:" }.Concat(Indent(body)).ToArray();
            string[] Var = { $"{name}: int = 7" };

            foreach (var s in new[] { StoreSpelling.Assign, StoreSpelling.Augmented, StoreSpelling.Walrus })
            {
                var text = StoreText(s, name);
                var py = s == StoreSpelling.Augmented ? PyOutcome.Unbound(name) : PyOutcome.Ran(JoinOut(15, 7));
                var main = new[] { "f()", $"print({name})" };
                yield return Cell($"{s}/above", Var.Concat(Fn(text, $"print({name})")).ToList(), main, Refuse(py, "N6"), FormEnum(s));
                yield return Cell($"{s}/below", Fn(text, $"print({name})").Concat(Var).ToList(), main, Refuse(py, "N6"), FormEnum(s));
                object written = s == StoreSpelling.Augmented ? 8 : 15;
                var through = PyOutcome.Ran(JoinOut(written, written));
                yield return Cell($"{s}/global", Var.Concat(Fn($"global {name}", text, $"print({name})")).ToList(), main,
                    new Expected(SharpyTag.MustRun, through.Value, through, "N6"), FormEnum(s));
            }

            // No binding of the name: a function local, and the builtin everywhere else.
            var noBinding = PyOutcome.Ran(JoinOut(15, result));
            yield return Cell("assign/no-binding", Fn($"{name} = 15", $"print({name})"), new[] { "f()", $"print({name}({args}))" },
                new Expected(SharpyTag.MustRun, noBinding.Value, noBinding, "N5"), StoreForm.Assign);

            // A local visible from its binding, called as the builtin: a type error in both.
            yield return Cell("walrus/call", Fn($"({name} := 15)", $"print({name}({args}))"), new[] { "f()" },
                Refuse(PyOutcome.Other("TypeError"), "N5"), StoreForm.Walrus);
            yield return Cell("const/call", Fn($"const {name}: int = 15", $"print({name}({args}))"), new[] { "f()" },
                Refuse(PyOutcome.Other("TypeError"), "N5"), StoreForm.LetOrVar);
        }
    }

