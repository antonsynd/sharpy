    private static readonly BindingKind[] LocalKinds =
    {
        BindingKind.LocalVar, BindingKind.LocalLet, BindingKind.LocalLiteralConst, BindingKind.LocalComputedConst,
        BindingKind.LocalDef, BindingKind.LambdaTypedLocal,
    };

    /// <summary>LOCAL's outer axis (finding 3): the roster's generated values, the pruned ones named there. The Builtin
    /// outer's name is the axis, so it has its own arm below.</summary>
    private static readonly BindingKind[] LocalOuters = NameResolutionRosters.LocalOuter
        .Where(e => e.Value.Generated && e.Key != BindingKind.Builtin)
        .Select(e => e.Key)
        .OrderBy(k => k)
        .ToArray();

    /// <summary>The bodies LOCAL's kind × outer × read product runs at: one of each function-like family. The whole of roster
    /// 4 is crossed with the construct targets, on one outer (D3.e's pruning; the read product does not change per body,
    /// since a local binds alike in every function-like scope).</summary>
    private static readonly ReadPosition[] LocalBodies =
    {
        ReadPosition.FunctionBody, ReadPosition.MethodBody, ReadPosition.NestedDefInFunction,
    };

    private static IEnumerable<ReadPosition> LocalBodiesFor(LocalTarget target) =>
        NameResolutionRosters.LocalBodies
            .Where(e => e.Value.Image.Contains(target) && IsStatementBody(e.Key))
            .Select(e => e.Key)
            .OrderBy(p => p);

    private static List<string> LocalDecl(BindingKind k, ReadName n)
    {
        var value = BindingValue(k, n);
        var name = n.Name;
        switch (k)
        {
            case BindingKind.LocalVar:
                return new() { $"{name}: int = {value}" };
            case BindingKind.LocalLet:
                return new() { $"let {name} = {value}" };
            case BindingKind.LocalLiteralConst:
                return new() { $"const {name}: int = {value}" };
            case BindingKind.LocalComputedConst:
                return new() { $"const {name}: int = seven() + {value - 7}" };
            case BindingKind.LocalDef:
                return new() { $"def {name}({n.Params}) -> int:", $"    return {value}" };
            case BindingKind.LambdaTypedLocal:
                if (!n.IsBuiltin)
                    return new() { $"{name}: () -> int = lambda: {value}" };
                var (types, lambdaParams) = name == "abs" ? ("int", "a0") : ("str", "a0");
                return new() { $"{name}: ({types}) -> int = lambda {lambdaParams}: {value}" };
            default:
                throw new ArgumentOutOfRangeException(nameof(k));
        }
    }

    private static NameCell LocalProgram(string id, BindingKind binding, BindingKind outer, ReadPosition body, IReadOnlyList<string> stmts, Expected e, string? shape, ReadName n, LocalTarget? construct = null)
    {
        var members = outer is BindingKind.StaticMethod or BindingKind.StaticField ? MemberDecl(outer, n) : new List<string>();
        var effectiveBody = stmts;
        if (outer == BindingKind.EnclosingLocal)
        {
            // The nested def holds the local; its enclosing function holds the outer binding of the name.
            var inner = new List<string> { "def g1() -> None:" };
            inner.AddRange(Indent(stmts));
            inner.Insert(0, $"{n.Name}: int = 13");
            inner.Add("g1()");
            effectiveBody = inner;
        }
        var (host, call) = Host(body, effectiveBody, members);
        var lines = new List<string>();
        if (stmts.Any(s => s.Contains("f0(out let", StringComparison.Ordinal)))
            lines.AddRange(OutLetHelper);
        if (stmts.Any(s => s.Contains("CM()", StringComparison.Ordinal)))
            lines.AddRange(new[] { "class CM:", "    def __enter__(self) -> int:", "        return 7", "    def __exit__(self) -> None:", "        pass" });
        if (IsModuleLevel(outer))
            lines.AddRange(ModuleDecl(outer, n));
        lines.AddRange(host);
        return new NameCell
        {
            Id = id,
            Family = Family.Local,
            Source = WithHelpers(Join(lines) + MainBlock(call.ToArray())),
            Tag = e.Tag,
            Model = e.Model,
            Python = e.Python,
            Rule = e.Rule,
            Deviation = e.Deviation,
            Target = binding,
            Outer = outer,
            Position = body,
            Construct = construct,
            Shape = shape,
        };
    }

    private static string ClassOf(BindingKind outer) => outer switch
    {
        BindingKind.None or BindingKind.StaticMethod or BindingKind.StaticField => "none",
        BindingKind.EnclosingLocal => "enclosing",
        BindingKind.Builtin => "builtin",
        _ => "module",
    };

    private static IEnumerable<NameCell> LocalCells()
    {
        var plain = ReadName.Plain;

        foreach (var k in LocalKinds)
        {
            var form = FormOf(k);
            var own = ReadText(form, "", plain);
            int value = ValueOf(k);
            foreach (var u in LocalOuters)
                foreach (var body in u is BindingKind.StaticMethod or BindingKind.StaticField ? new[] { ReadPosition.MethodBody } : LocalBodies)
                {
                    string Id(string read) => CellId("local", k, read, $"outer={u}", body);

                    // Read below the binding: the innermost binding, in both languages.
                    yield return LocalProgram(Id("below"), k, u, body, LocalDecl(k, plain).Append($"print({own})").ToList(), Run(value, "N1-innermost"), null, plain);

                    // Read above the binding: python's UnboundLocalError at every outer.
                    var aboveForm = u is BindingKind.None or BindingKind.StaticMethod or BindingKind.StaticField or BindingKind.EnclosingLocal
                        ? form
                        : (Form)Math.Max((int)form, (int)FormOf(u));
                    var above = new List<string> { $"print({ReadText(aboveForm, "", plain)})" };
                    above.AddRange(LocalDecl(k, plain));
                    above.Add($"print({own})");
                    var python = PyOutcome.Unbound("x");
                    if (ClassOf(u) == "none" || IsCallableKind(k))
                        yield return LocalProgram(Id("above"), k, u, body, above, Refuse(python, IsCallableKind(k) ? "S3" : "N5"), null, plain);
                    else
                        yield return LocalProgram(Id("above"), k, u, body, above, new Expected(SharpyTag.Unruled, null, python, "unruled:N5-before-binding"), $"before-binding:{ClassOf(u)}", plain);

                    // Read from a nested def and a lambda called after the binding, the binding above the def.
                    var nested = LocalDecl(k, plain);
                    nested.AddRange(new[] { "def g() -> int:", $"    return {own}", "print(g())" });
                    yield return LocalProgram(Id("nested-def"), k, u, body, nested, Run(value, "N1-innermost"), null, plain);
                    var lambda = LocalDecl(k, plain);
                    lambda.AddRange(new[] { $"h: () -> int = lambda: {own}", "print(h())" });
                    yield return LocalProgram(Id("lambda"), k, u, body, lambda, Run(value, "N1-innermost"), null, plain);
                }
        }

        // The Builtin outer: a local spelled like the builtin (the name is the axis, so the read carries its arguments).
        foreach (var (name, args, pars, result) in Builtins)
        {
            var n = new ReadName(name, args, pars, result);
            foreach (var k in LocalKinds)
                foreach (var body in LocalBodies)
                {
                    var own = ReadText(FormOf(k), "", n);
                    var builtinCall = ReadText(Form.Call, "", n);
                    string Id(string read) => CellId("local", k, read, "outer=Builtin", body, name);
                    yield return LocalProgram(Id("below"), k, BindingKind.Builtin, body, LocalDecl(k, n).Append($"print({own})").ToList(), Run(BuiltinBindingValue, "N1-innermost"), null, n);
                    var above = new List<string> { $"print({builtinCall})" };
                    above.AddRange(LocalDecl(k, n));
                    above.Add($"print({own})");
                    var python = PyOutcome.Unbound(name);
                    if (IsCallableKind(k))
                        yield return LocalProgram(Id("above"), k, BindingKind.Builtin, body, above, Refuse(python, "S3"), null, n);
                    else
                        yield return LocalProgram(Id("above"), k, BindingKind.Builtin, body, above, new Expected(SharpyTag.Unruled, null, python, "unruled:N5-before-binding"), "before-binding:builtin", n);
                }
        }

        // Self: a local def recursing; a lambda-typed local reading itself is the N5 order=self question.
        foreach (var body in LocalBodies)
        {
            yield return LocalProgram(CellId("local", BindingKind.LocalDef, "self", body), BindingKind.LocalDef, BindingKind.None, body,
                new[] { "def x(k: int) -> int:", "    return 0 if k == 0 else x(k - 1) + 1", "print(x(3))" }, Run(3, "N5"), null, plain);
            yield return LocalProgram(CellId("local", BindingKind.LambdaTypedLocal, "self", body), BindingKind.LambdaTypedLocal, BindingKind.None, body,
                new[] { "x: (int) -> int = lambda k: x(k - 1) + 1 if k > 0 else 0", "print(x(3))" },
                new Expected(SharpyTag.Unruled, null, PyOutcome.Ran(3), "unruled:N5-self"), "lambda-self", plain);
        }

        // L28: a nested def reading an enclosing local declared below the def but bound before the call.
        foreach (var u in new[] { BindingKind.None, BindingKind.ModuleVar })
            foreach (var body in LocalBodies)
                yield return LocalProgram(CellId("local", "L28", $"outer={u}", body), BindingKind.EnclosingLocal, u, body,
                    new[] { "def g() -> int:", "    return x", "x: int = 15", "print(g())" },
                    new Expected(SharpyTag.Unruled, null, PyOutcome.Ran(15), "unruled:L28"), "L28", plain);

        foreach (var cell in ConstructTargetCells())
            yield return cell;

        // LocalBodies' one lambda row: a comprehension target inside a stored lambda's body, the name read outside it.
        foreach (var u in new[] { BindingKind.None, BindingKind.ModuleVar })
        {
            var read = u == BindingKind.None ? "ys[0]" : "x";
            var value = u == BindingKind.None ? 1 : ValueOf(u);
            yield return LocalProgram(CellId("local", "lambda-comprehension", $"outer={u}"), BindingKind.Inner, u, ReadPosition.FunctionBody,
                new[] { "g: () -> list[int] = lambda: [x for x in [1, 2]]", "ys: list[int] = g()", $"print({read})" },
                Run(value, "N1"), null, plain) with
            { Position = ReadPosition.LambdaStored, Construct = LocalTarget.Comprehension };
        }
        foreach (var cell in LetInConstructCells())
            yield return cell;

        // A closure created in a loop or a comprehension and called after it.
        foreach (var body in LocalBodies)
        {
            yield return LocalProgram(CellId("local", "closure-in-loop", body), BindingKind.LocalVar, BindingKind.None, body,
                new[] { "fs: list[() -> int] = []", "for i in range(3):", "    fs.append(lambda: i)", "print([g0() for g0 in fs])" },
                new Expected(SharpyTag.MustRun, "[0, 1, 2]", PyOutcome.Ran("[2, 2, 2]"), "N5", "loop-variable-fresh-per-iteration"), null, plain);
            yield return LocalProgram(CellId("local", "closure-in-comprehension", body), BindingKind.LocalVar, BindingKind.None, body,
                new[] { "fs: list[() -> int] = [lambda: i for i in range(3)]", "print([g0() for g0 in fs])" },
                new Expected(SharpyTag.MustRun, "[0, 1, 2]", PyOutcome.Ran("[2, 2, 2]"), "N5", "loop-variable-fresh-per-iteration"), null, plain);
        }
    }

    private static (string[] Lines, object? Last) ConstructOf(LocalTarget t, string name) => t switch
    {
        LocalTarget.For => (new[] { $"for {name} in range(3):", "    pass" }, 2),
        LocalTarget.ExceptAs => (new[] { "try:", "    raise ValueError(\"v\")", $"except ValueError as {name}:", "    pass" }, null),
        LocalTarget.WithAs => (new[] { $"with CM() as {name}:", "    pass" }, 7),
        LocalTarget.Comprehension => (new[] { $"ys: list[int] = [{name} for {name} in [1, 2]]" }, null),
        LocalTarget.MatchCapture => (new[] { "match 2:", $"    case {name}:", "        pass" }, 2),
        LocalTarget.AsPatternCapture => (new[] { "match 1:", $"    case 1 as {name}:", "        pass" }, 1),
        LocalTarget.OutLet => (new[] { $"f0(out let {name})" }, 15),
        _ => throw new ArgumentOutOfRangeException(nameof(t)),
    };

    private static IEnumerable<NameCell> ConstructTargetCells()
    {
        var plain = ReadName.Plain;
        var outers = new[] { BindingKind.None, BindingKind.ModuleVar, BindingKind.ModuleProperty, BindingKind.ModuleLiteralConst, BindingKind.LocalVar, BindingKind.EnclosingLocal };

        foreach (var t in Enum.GetValues<LocalTarget>())
            foreach (var body in LocalBodiesFor(t))
            {
                var (construct, last) = ConstructOf(t, "x");
                foreach (var u in LocalBodies.Contains(body) ? outers : new[] { BindingKind.ModuleVar })
                {
                    var stmts = new List<string>();
                    if (u == BindingKind.LocalVar)
                        stmts.Add("x: int = 13");
                    stmts.AddRange(construct);
                    stmts.Add("print(x)");
                    var moduleOrLocal = u == BindingKind.None ? (int?)null : ValueOf(u == BindingKind.LocalVar ? BindingKind.EnclosingLocal : u);

                    Expected e;
                    string? shape = null;
                    switch (t)
                    {
                        case LocalTarget.OutLet:
                            e = Run(15, "R-BM");
                            break;
                        case LocalTarget.Comprehension:
                            e = moduleOrLocal is int visible
                                ? Run(visible, "N1")
                                : Refuse(PyOutcome.Name("x"), "N5");
                            break;
                        case LocalTarget.MatchCapture:
                        case LocalTarget.AsPatternCapture:
                            e = new Expected(SharpyTag.Unruled, null, PyOutcome.Ran(last!), "unruled:N5-match-capture");
                            shape = $"match-capture:{(u == BindingKind.None ? "none" : "visible")}";
                            break;
                        default:
                            var python = t == LocalTarget.ExceptAs ? PyOutcome.Unbound("x") : PyOutcome.Ran(last!);
                            if (u == BindingKind.None)
                            {
                                string? deviation = t switch
                                {
                                    LocalTarget.For => "block-scoping-for-loop-variable",
                                    LocalTarget.WithAs => "block-scoping-with",
                                    _ => null,
                                };
                                e = new Expected(SharpyTag.MustRefuse, null, python, "N5", deviation);
                            }
                            else
                            {
                                e = Refuse(python, "S2");
                            }
                            break;
                    }

                    yield return LocalProgram(CellId("local", t, "after-block", $"outer={u}", body),
                        BindingKind.LocalVar, u == BindingKind.LocalVar ? BindingKind.LocalVar : u, body, stmts, e, shape, plain, t);
                }

                // Read inside the block, and no later read: legal in both.
                if (t is LocalTarget.For)
                {
                    yield return LocalProgram(CellId("local", t, "inside", "outer=ModuleVar", body), BindingKind.LocalVar, BindingKind.ModuleVar, body,
                        new[] { "for x in range(2):", "    print(x)" }, new Expected(SharpyTag.MustRun, "0\n1", PyOutcome.Ran("0\n1"), "N5"), null, plain, t);
                }
                if (t is LocalTarget.WithAs)
                {
                    yield return LocalProgram(CellId("local", t, "inside", "outer=ModuleVar", body), BindingKind.LocalVar, BindingKind.ModuleVar, body,
                        new[] { "with CM() as x:", "    print(x)" }, Run(7, "N5"), null, plain, t);
                }
                if (t is LocalTarget.ExceptAs)
                {
                    yield return LocalProgram(CellId("local", t, "inside", "outer=ModuleVar", body), BindingKind.LocalVar, BindingKind.ModuleVar, body,
                        new[] { "try:", "    raise ValueError(\"v\")", "except ValueError as x:", "    print(1)" }, Run(1, "N5"), null, plain, t);
                }
            }

        // S2 × Builtin: is a builtin a visible binding the target reuses? Only the comprehension is agreed.
        foreach (var (name, args, pars, result) in Builtins)
        {
            var n = new ReadName(name, args, pars, result);
            foreach (var t in new[] { LocalTarget.For, LocalTarget.WithAs, LocalTarget.ExceptAs, LocalTarget.MatchCapture, LocalTarget.AsPatternCapture, LocalTarget.Comprehension })
                foreach (var body in new[] { ReadPosition.FunctionBody, ReadPosition.MethodBody })
                {
                    var (construct, _) = ConstructOf(t, name);
                    var stmts = construct.Append($"print({name}({args}))").ToList();
                    var e = t == LocalTarget.Comprehension
                        ? Run(result, "N1")
                        // `except … as abs` deletes the name, so python's later call is unbound; the other targets call an int.
                        : new Expected(SharpyTag.Unruled, null, t == LocalTarget.ExceptAs ? PyOutcome.Unbound(name) : PyOutcome.Other("TypeError"), "unruled:S2-builtin");
                    var shape = t == LocalTarget.Comprehension ? null : t is LocalTarget.MatchCapture or LocalTarget.AsPatternCapture ? "match-capture:builtin" : "s2-builtin";
                    yield return LocalProgram(CellId("local", t, "after-block", "outer=Builtin", body, name), BindingKind.LocalVar, BindingKind.Builtin, body, stmts, e, shape, n, t);
                }
        }
    }

    /// <summary>A construct body's Block family, and the deviation row that names it (null = no row exists: `unruled`, #2426).</summary>
