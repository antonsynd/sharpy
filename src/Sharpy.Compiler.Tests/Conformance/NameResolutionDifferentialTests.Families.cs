    /// <summary>Does the cell's shape label name the axes the cell is actually on? The label alone proves nothing: an arm can
    /// spell any listed name, so each entry reads the properties that define its question.</summary>
    internal static bool UnruledAxesHold(NameCell c)
    {
        var shape = c.Shape ?? "";
        var parts = shape.Split(':');
        var capture = c.Construct is LocalTarget.MatchCapture or LocalTarget.AsPatternCapture;
        switch (parts[0])
        {
            case "L28":
                return c.Family == Family.Local && c.Target == BindingKind.EnclosingLocal && c.Outer is BindingKind.None or BindingKind.ModuleVar;
            case "lambda-self":
                return c.Family == Family.Local && c.Target == BindingKind.LambdaTypedLocal && c.Outer == BindingKind.None
                    && c.Id.Contains("/self/", StringComparison.Ordinal);
            case "match-capture":
                return c.Family == Family.Local && capture && parts[1] == (c.Outer switch
                {
                    BindingKind.None => "none",
                    BindingKind.Builtin => "builtin",
                    _ => "visible",
                });
            case "before-binding":
                return c.Family == Family.Local && c.Construct == null && !IsCallableKind(c.Target)
                    && c.Id.Contains("/above/", StringComparison.Ordinal) && ClassOf(c.Outer) == parts[1];
            case "rowless-let":
                return c.Family == Family.Local && c.Target == BindingKind.LocalLet
                    && c.Id.Contains($"/let-in/{parts[1]}/", StringComparison.Ordinal)
                    && BlockShapes.Any(b => b.Family == parts[1] && b.Row == null);
            case "s2-builtin":
                return c.Family == Family.Local && c.Outer == BindingKind.Builtin
                    && c.Construct is LocalTarget.For or LocalTarget.WithAs or LocalTarget.ExceptAs;
            case "store-non-writable":
                return c.Family == Family.Store && IsNonWritableByMeaning(c.Outer) && c.Outer.ToString() == parts[1]
                    && (parts[2] == "global"
                        ? c.Id.Contains("/global/", StringComparison.Ordinal)
                        : c.Id.StartsWith($"store/{parts[2]}/", StringComparison.Ordinal) && c.Id.Contains("/no-decl/", StringComparison.Ordinal));
            case "seed":
                return c.Family == Family.Seed && c.Id == $"seed/{parts[1]}";
            default:
                return false;
        }
    }

    /// <summary>D2's deviation row, as a closed set of axes per ledger id: a row existing in the ledger is not enough, because any
    /// must-run cell could otherwise cite one and turn a wrong model into Match with python agreeing.</summary>
    internal static bool DeviationAxesHold(NameCell c)
    {
        if (c.Family == Family.Seed)
            return SeedDeviations.GetValueOrDefault(c.Id["seed/".Length..]) == c.Deviation;
        var afterBlock = c.Family == Family.Local && c.Outer == BindingKind.None && c.Id.Contains("/after-block/", StringComparison.Ordinal);
        var letInItsBlock = c.Family == Family.Local && c.Target == BindingKind.LocalLet
            && BlockShapes.Any(b => b.Row == c.Deviation && c.Id.Contains($"/let-in/{b.Family}/", StringComparison.Ordinal));
        switch (c.Deviation)
        {
            case "loop-variable-fresh-per-iteration":
                return c.Family == Family.Local && c.Id.StartsWith("local/closure-in-", StringComparison.Ordinal);
            case "block-scoping-for-loop-variable":
                return afterBlock && c.Construct == LocalTarget.For;
            case "block-scoping-with":
                return (afterBlock && c.Construct == LocalTarget.WithAs) || letInItsBlock;
            case "walrus-in-comprehension-scope":
                return c.Family == Family.Store && c.Form == StoreForm.Walrus && c.Position == ReadPosition.ComprehensionElement;
            default:
                return letInItsBlock;
        }
    }

    private static IEnumerable<string> ClosedSetFailures(IReadOnlyList<NameCell> pool)
    {
        foreach (var c in pool.Where(c => c.Deviation != null && !DeviationAxesHold(c)).Take(20))
            yield return $"DeviationAxes: {c.Id} cites {c.Deviation} and its axes are not that row's";

        // N3's cycles are the one question where a throw also keeps the promise. Any other rule under this tag would read a throw as agreement.
        foreach (var c in pool.Where(c => c.Tag == SharpyTag.MustRefuseOrThrow && c.Rule is not ("N3-cycle" or "seed")).Take(20))
            yield return $"MustRefuseOrThrow: {c.Id} under rule {c.Rule}, and only an N3 cycle may refuse or throw";

        foreach (var c in pool.Where(c => c.Tag == SharpyTag.MayRefuse && !IsMayRefuseShape(c)).Take(20))
            yield return $"MayRefuseShapes: {c.Id} is tagged may-refuse, and only READ × module let may be";
        var mayRefuseCount = pool.Count(c => c.Tag == SharpyTag.MayRefuse && !IsMayRefuseShape(c));
        if (mayRefuseCount > 20)
            yield return $"MayRefuseShapes: … {mayRefuseCount} cells in total";
        if (!pool.Any(c => c.Tag == SharpyTag.MayRefuse))
            yield return "MayRefuseShapes: the entry has no generated cell";

        var unruled = pool.Where(c => c.Tag == SharpyTag.Unruled).ToList();
        var unlisted = unruled.Where(c => c.Shape == null || !UnruledShapeCounts.ContainsKey(c.Shape)).ToList();
        foreach (var c in unlisted.Take(20))
            yield return $"UnruledShapes: {c.Id} is tagged unruled with shape '{c.Shape}', which is no listed shape";
        if (unlisted.Count > 20)
            yield return $"UnruledShapes: … {unlisted.Count} cells in total";
        var misplaced = unruled.Except(unlisted).Where(c => !UnruledAxesHold(c)).ToList();
        foreach (var c in misplaced.Take(20))
            yield return $"UnruledShapes: {c.Id} is labelled '{c.Shape}' and its axes are not that question's";
        if (misplaced.Count > 20)
            yield return $"UnruledShapes: … {misplaced.Count} misplaced cells in total";
        var counts = unruled.Where(c => c.Shape != null).GroupBy(c => c.Shape!, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);
        foreach (var (shape, pinned) in UnruledShapeCounts.Where(e => counts.GetValueOrDefault(e.Key) != e.Value))
            yield return $"UnruledShapes: '{shape}' is pinned at {pinned} cells and generates {counts.GetValueOrDefault(shape)}";
    }

    /// <summary>The report's coverage statement: cells per roster value on each axis.</summary>
    private static object RosterReport(IReadOnlyList<CellResult> results) => new
    {
        censuses = new
        {
            variableSymbolBools = NameResolutionRosters.VariableSymbolBoolCensus,
            functionSymbolDeclaredBools = NameResolutionRosters.FunctionSymbolDeclaredBoolCensus,
            binderSites = NameResolutionRosters.BinderSiteCensus,
            typeAnnotationScalar = NameResolutionRosters.TypeAnnotationScalarCensus,
            typeAnnotationCollection = NameResolutionRosters.TypeAnnotationCollectionCensus,
            patternSubclasses = NameResolutionRosters.PatternSubclassCensus,
            statementSubclasses = NameResolutionRosters.StatementSubclassCensus,
            blockFamilies = NameResolutionRosters.BlockFamilyCensus,
            functionLikeFamilies = NameResolutionRosters.FunctionLikeFamilyCensus,
        },
        excluded = new
        {
            storeOuter = NameResolutionRosters.StoreOuter.Where(e => !e.Value.Generated).ToDictionary(e => e.Key.ToString(), e => e.Value.Reason),
            localOuter = NameResolutionRosters.LocalOuter.Where(e => !e.Value.Generated).ToDictionary(e => e.Key.ToString(), e => e.Value.Reason),
            storeBodies = NameResolutionRosters.StoreBodies.Where(e => e.Value.Excluded != null).ToDictionary(e => e.Key.ToString(), e => e.Value.Reason),
            localBodies = NameResolutionRosters.LocalBodies.Where(e => e.Value.Excluded != null).ToDictionary(e => e.Key.ToString(), e => e.Value.Reason),
            patterns = NameResolutionRosters.PatternNotes,
            readAxes = PrunedReadAxes,
        },
        targets = results.GroupBy(r => r.Cell.Target.ToString()).OrderBy(g => g.Key, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.Count()),
        outers = results.GroupBy(r => r.Cell.Outer.ToString()).OrderBy(g => g.Key, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.Count()),
        positions = results.Where(r => r.Cell.Position != null).GroupBy(r => r.Cell.Position!.Value.ToString()).OrderBy(g => g.Key, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.Count()),
        storeForms = results.Where(r => r.Cell.Form != null).GroupBy(r => r.Cell.Form!.Value.ToString()).OrderBy(g => g.Key, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.Count()),
        constructs = results.Where(r => r.Cell.Construct != null).GroupBy(r => r.Cell.Construct!.Value.ToString()).OrderBy(g => g.Key, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.Count()),
    };

    /// <summary>Every roster value the generator owes a cell has one (D3: a value with 0 cells and no exclusion is red).
    /// Each axis is read from the roster, so widening a roster without generating its cells goes red here.</summary>
    private static IEnumerable<string> RosterFedFailures(IReadOnlyList<NameCell> pool)
    {
        var positions = pool.Where(c => c.Position != null).Select(c => c.Position!.Value).ToHashSet();
        foreach (var p in Enum.GetValues<ReadPosition>().Where(p => !positions.Contains(p)))
            yield return $"ReadPosition {p} has no generated cell";

        // Roster 6. The pattern's own type is roster 7's: TYPEMEMBER's pattern cells are its feed, read just below.
        var typePositions = pool.Where(c => c.TypeAt != null).Select(c => c.TypeAt!.Value).ToHashSet();
        foreach (var p in Enum.GetValues<TypePosition>().Where(p => !typePositions.Contains(p) && p != TypePosition.PatternType))
            yield return $"TypePosition {p} has no generated cell";

        // Roster 8: a Block family that hosts a `let` has its shape, with a cell on it.
        foreach (var (family, entry) in NameResolutionRosters.BlockFamilies.Where(e => e.Value.Image.Any(i => i.LetInBody != null)))
            if (!pool.Any(c => c.Family == Family.Local && c.Id.Contains($"/let-in/{family}/", StringComparison.Ordinal))
                && entry.Excluded == null)
                yield return $"BlockFamily {family} hosts a let and has no LOCAL cell";

        // READ's outer: every module-level kind is generated or pruned with its reason, and a pruned entry names something real.
        foreach (var k in NameResolutionRosters.ModuleLevelKinds.Where(k => !ModuleOuters.Contains(k) && !PrunedReadAxes.ContainsKey($"outer {k}")))
            yield return $"ModuleLevelKinds {k} is neither a generated READ outer nor pruned";
        foreach (var key in PrunedReadAxes.Keys)
        {
            var parts = key.Split(' ');
            var real = parts[0] == "outer"
                ? Enum.TryParse<BindingKind>(parts[1], out var k) && NameResolutionRosters.ModuleLevelKinds.Contains(k) && !ModuleOuters.Contains(k)
                : key.StartsWith("Builtin name ", StringComparison.Ordinal) && Builtins.All(b => b.Name != parts[2]);
            if (!real)
                yield return $"PrunedReadAxes '{key}' names nothing the generator left out";
        }

        var forms = pool.Where(c => c.Form != null).Select(c => c.Form!.Value).ToHashSet();
        foreach (var f in Enum.GetValues<StoreForm>().Where(f => !forms.Contains(f)))
            yield return $"StoreForm {f} has no generated cell";

        var constructs = pool.Where(c => c.Construct != null).Select(c => c.Construct!.Value).ToHashSet();
        foreach (var t in Enum.GetValues<LocalTarget>().Where(t => !constructs.Contains(t)))
            yield return $"LocalTarget {t} has no generated cell";

        var kinds = pool.SelectMany(c => new[] { c.Target, c.Outer }).ToHashSet();
        foreach (var k in Enum.GetValues<BindingKind>().Where(k => !kinds.Contains(k) && k != BindingKind.Constructor))
            yield return $"BindingKind {k} has no generated cell";

        var store = pool.Where(c => c.Family == Family.Store).ToList();
        var local = pool.Where(c => c.Family == Family.Local).ToList();
        foreach (var (k, _) in NameResolutionRosters.StoreOuter.Where(e => e.Value.Generated && !store.Any(c => c.Outer == e.Key)))
            yield return $"StoreOuter {k} is generated by the roster and has no STORE cell";
        foreach (var (k, _) in NameResolutionRosters.LocalOuter.Where(e => e.Value.Generated && !local.Any(c => c.Outer == e.Key)))
            yield return $"LocalOuter {k} is generated by the roster and has no LOCAL cell";
        foreach (var (body, e) in NameResolutionRosters.StoreBodies)
            foreach (var f in e.Image.Where(f => !store.Any(c => c.Position == body && c.Form == f)))
                yield return $"StoreBodies {body} × {f} is in the roster and has no STORE cell";
        foreach (var (body, e) in NameResolutionRosters.LocalBodies)
            foreach (var t in e.Image.Where(t => !local.Any(c => c.Position == body && c.Construct == t)))
                yield return $"LocalBodies {body} × {t} is in the roster and has no LOCAL cell";

        // Every kind a generated cell carries is a roster value: the roster's image, read through its groups.
        var rosterKinds = NameResolutionRosters.ModuleLevelKinds
            .Concat(NameResolutionRosters.TypeLevelKinds)
            .Concat(NameResolutionRosters.InstanceKinds)
            .Concat(NameResolutionRosters.PositionLocalKinds)
            .Concat(NameResolutionRosters.NonSymbolKinds)
            .Append(BindingKind.Builtin)
            .ToHashSet();
        foreach (var k in kinds.Where(k => !rosterKinds.Contains(k)))
            yield return $"BindingKind {k} is carried by a generated cell and is in no roster group";

        // A generated cell never leaves its axis: an invented outer, a type-level outer at a free function's body and a form the
        // body cannot host are all red. LocalVar is the target-scope axis's same-function binding, never an outer of its own.
        foreach (var c in store.Where(c => c.Outer != BindingKind.LocalVar))
        {
            if (!NameResolutionRosters.StoreOuter.TryGetValue(c.Outer, out var m) || !m.Generated)
                yield return $"{c.Id}: outer {c.Outer} is not generated on StoreOuter";
            else if (m.ClassEnclosedBodiesOnly && c.Position is ReadPosition p && !NameResolutionRosters.ClassEnclosedBodies.Contains(p))
                yield return $"{c.Id}: outer {c.Outer} is class-enclosed and {p} is not";
            // A comprehension element is the walrus's own position sub-axis (its deviation row's feeder), not a body.
            if (c.Position is ReadPosition body && body != ReadPosition.ComprehensionElement && c.Form is StoreForm f
                && !(NameResolutionRosters.StoreBodies.TryGetValue(body, out var e) && e.Image.Contains(f)))
                yield return $"{c.Id}: {body} × {f} is not in StoreBodies";
        }
        foreach (var c in local.Where(c => c.Outer != BindingKind.LocalVar))
        {
            if (!NameResolutionRosters.LocalOuter.TryGetValue(c.Outer, out var m) || !m.Generated)
                yield return $"{c.Id}: outer {c.Outer} is not generated on LocalOuter";
            else if (m.ClassEnclosedBodiesOnly && c.Position is ReadPosition p && !NameResolutionRosters.ClassEnclosedBodies.Contains(p))
                yield return $"{c.Id}: outer {c.Outer} is class-enclosed and {p} is not";
            if (c.Position is ReadPosition body && c.Construct is LocalTarget t
                && !(NameResolutionRosters.LocalBodies.TryGetValue(body, out var e) && e.Image.Contains(t)))
                yield return $"{c.Id}: {body} × {t} is not in LocalBodies";
        }

        // Every pattern that carries a name has a cell, or a note saying why it cannot have one.
        var typeMember = pool.Where(c => c.Family == Family.TypeMember).ToList();
        foreach (var (name, cls) in NameResolutionRosters.Patterns.Where(e => e.Value != PatternClass.CarriesNoName && !NameResolutionRosters.PatternNotes.ContainsKey(e.Key)))
            if (!typeMember.Any(c => c.Id.Contains($"pattern/{name}", StringComparison.Ordinal)))
                yield return $"Pattern {name} ({cls}) has no TYPEMEMBER cell and no note";
    }
