    /// <summary>The roster-4 bodies hosting <paramref name="form"/>, read from the roster and never listed here.</summary>
    private static IEnumerable<ReadPosition> StoreBodiesFor(StoreForm form) =>
        NameResolutionRosters.StoreBodies
            .Where(e => e.Value.Image.Contains(form) && IsStatementBody(e.Key))
            .Select(e => e.Key)
            .OrderBy(p => p);

    /// <summary>A lambda's body is one expression: its walrus and comprehension cells are generated by their own arms.</summary>
    private static bool IsStatementBody(ReadPosition p) =>
        p is not (ReadPosition.LambdaStored or ReadPosition.LambdaImmediate or ReadPosition.LambdaPassed);

    /// <summary>Hosts <paramref name="body"/> at a body position: its module-level lines and the statements <c>main</c>
    /// runs. <paramref name="members"/> are class-level declarations beside the host.</summary>
    private static (List<string> Lines, List<string> Call) Host(ReadPosition p, IReadOnlyList<string> body, IReadOnlyList<string>? members = null)
    {
        var m = members ?? Array.Empty<string>();
        var lines = new List<string>();
        var call = new List<string>();
        switch (p)
        {
            case ReadPosition.FunctionBody:
                lines.Add("def f() -> None:");
                lines.AddRange(Indent(body));
                call.Add("f()");
                break;
            case ReadPosition.NestedDefInFunction:
                lines.AddRange(new[] { "def f() -> None:", "    def g() -> None:" });
                lines.AddRange(Indent(body, 8));
                lines.Add("    g()");
                call.Add("f()");
                break;
            case ReadPosition.GeneratorBody:
                lines.Add("def f() -> int:");
                lines.AddRange(Indent(body));
                lines.Add("    yield 1");
                call.Add("v0: list[int] = [g0 for g0 in f()]");
                break;
            case ReadPosition.MethodBody:
                lines.Add("class H:");
                lines.AddRange(Indent(m));
                lines.Add("    def f(self) -> None:");
                lines.AddRange(Indent(body, 8));
                call.Add("H().f()");
                break;
            case ReadPosition.StaticMethodBody:
                lines.Add("class H:");
                lines.AddRange(Indent(m));
                lines.AddRange(new[] { "    @static", "    def f() -> None:" });
                lines.AddRange(Indent(body, 8));
                call.Add("H.f()");
                break;
            case ReadPosition.InitBody:
                lines.Add("class H:");
                lines.AddRange(Indent(m));
                lines.Add("    def __init__(self) -> None:");
                lines.AddRange(Indent(body, 8));
                call.Add("h0: H = H()");
                break;
            case ReadPosition.AccessorGetBody:
                lines.Add("class H:");
                lines.AddRange(Indent(m));
                lines.Add("    property get f(self) -> int:");
                lines.AddRange(Indent(body, 8));
                lines.Add("        return 0");
                call.Add("v0: int = H().f");
                break;
            case ReadPosition.AccessorSetBody:
                lines.Add("class H:");
                lines.AddRange(Indent(m));
                lines.Add("    property get f(self) -> int:");
                lines.Add("        return 0");
                lines.Add("    property set f(self, v9: int) -> None:");
                lines.AddRange(Indent(body, 8));
                call.Add("h0: H = H()");
                call.Add("h0.f = 1");
                break;
            case ReadPosition.ModuleAccessorBody:
                lines.Add("property get f() -> int:");
                lines.AddRange(Indent(body));
                lines.Add("    return 0");
                call.Add("v0: int = f");
                break;
            case ReadPosition.NestedDefInMethod:
                lines.Add("class H:");
                lines.AddRange(Indent(m));
                lines.AddRange(new[] { "    def f(self) -> None:", "        def g() -> None:" });
                lines.AddRange(Indent(body, 12));
                lines.Add("        g()");
                call.Add("H().f()");
                break;
            case ReadPosition.NestedClassMethodBody:
                lines.Add("class H:");
                lines.AddRange(Indent(m));
                lines.AddRange(new[] { "    class I:", "        def f(self) -> None:" });
                lines.AddRange(Indent(body, 12));
                call.Add("H.I().f()");
                break;
            default:
                throw new ArgumentOutOfRangeException(nameof(p), p, "not a body host");
        }
        return (lines, call);
    }

    private static readonly string[] OutLetHelper = { "def f0(v: out int) -> None:", "    v = 15" };

    /// <summary>The module-side read of an outer value after the store, in the form the kind admits.</summary>
    private static string? OuterRead(BindingKind outer, ReadName n) => outer switch
    {
        BindingKind.ModuleUnion or BindingKind.ModuleInterface => null,
        _ => ReadText(FormOf(outer), "", n),
    };

    private static string JoinOut(params object[] values) => string.Join("\n", values.Select(v => Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture)));

